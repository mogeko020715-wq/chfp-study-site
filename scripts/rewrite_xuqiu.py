def esc(s: str) -> str:
    # 只转义双引号；字符串里的 \n 是刻意保留的 TS 换行转义，不要再动反斜杠
    return s.replace('"', '\\"')


def main() -> None:
    src = PATH.read_text(encoding="utf-8")
    for old_stem, new_stem, new_answer in EDITS:
        needle = f'stem: "{esc(old_stem)}"'
        i = src.find(needle)
        if i < 0:
            raise SystemExit(f"未找到题干：{old_stem[:30]}")
        m = re.search(r'answer: "((?:[^"\\]|\\.)*)"', src[i:])
        if not m:
            raise SystemExit(f"未找到答案：{old_stem[:30]}")
        a_start, a_end = i + m.start(), i + m.end()
        src = src[:a_start] + f'answer: "{esc(new_answer)}"' + src[a_end:]
        src = src.replace(needle, f'stem: "{esc(new_stem)}"', 1)
        print(f"OK  {old_stem[:24]}…")
    PATH.write_text(src, encoding="utf-8")
    print(f"\n共改写 {len(EDITS)} 条")


if __name__ == "__main__":
    main()
